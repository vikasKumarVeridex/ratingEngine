/* ==========================================================================
   Live rate-table registry.

   Every entry reads straight off VX at render time — the same objects
   engine.js dereferences while rating — so this screen cannot drift from
   what actually gets charged. That distinction matters: the Rating Factors
   screen lists generated sample metadata with random default values, and
   Lookup Tables lists row counts without rows. Neither shows the numbers
   the engine rates on. This does.

   `neutral` flags the table's default/reference row so it's obvious which
   value applies when an answer doesn't move the factor.
   ========================================================================== */
